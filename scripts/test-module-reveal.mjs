import path from 'node:path';
import os from 'node:os';
import {pathToFileURL} from 'node:url';
import {mkdtemp,rm} from 'node:fs/promises';
const dashi=path.join(os.homedir(),'.codex/skills/dashiai-ppt/project');
const {chromium}=await import(pathToFileURL(path.join(dashi,'node_modules/playwright-core/index.mjs')));
const {getExportBrowserPath}=await import(pathToFileURL(path.join(dashi,'scripts/chrome-path.mjs')));
const browser=await chromium.launch({headless:true,executablePath:getExportBrowserPath()});
const temp=await mkdtemp(path.join(os.tmpdir(),'hppt-modules-'));
const page=await browser.newPage({viewport:{width:1920,height:1080}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const assert=(v,msg)=>{if(!v)throw Error(msg)};
const cards='#p05 .reader-duo > article';
try{
 await page.goto(process.argv[2],{waitUntil:'networkidle'});
 await page.evaluate(()=>{window.go(4);window.__htmlPptEditor.setEditing(true)});
 await page.locator('#p05 h1').click();
 await page.locator('[data-id="anim"]').click();
 await page.locator('[data-id="modulePick"]').click();
 await page.locator(cards).nth(0).locator('h2').click();
 assert(await page.locator(cards).nth(0).evaluate(n=>n.classList.contains('hppt-selected')),'未选中整个蓝色模块');
 const before=await page.locator(cards).nth(0).boundingBox();
 const edge=page.locator('.hppt-resize-box .hppt-move-edge[data-edge="n"]');
 const rect=await edge.boundingBox();
 await page.mouse.move(rect.x+30,rect.y+rect.height/2);await page.mouse.down();await page.mouse.move(rect.x+70,rect.y+rect.height/2+20,{steps:8});await page.mouse.up();
 const after=await page.locator(cards).nth(0).boundingBox();assert(Math.abs(after.x-before.x)>20,'整个模块不能拖动');
 await page.locator('[data-id="undo"]').click();
 await page.locator(cards).nth(0).locator('h2').click();
 await page.locator('[data-id="multiPick"]').click();
 await page.locator(cards).nth(1).locator('h2').click();
 await page.locator('[data-id="modulePick"]').click();
 await page.locator('#p05 .takeaway').click();
 assert(await page.locator('#p05 .hppt-multi-selected').count()===3,'多选模块与文字失败');
 await page.locator('[data-id="revealTogether"]').click();
 const group=await page.locator(cards).nth(0).getAttribute('data-hppt-reveal-group');
 assert(group&&await page.locator('#p05 [data-hppt-reveal-group]').count()===3,'未建立同步出现组');
 await page.locator('[data-id="earlier"]').click();
 assert(await page.locator('#p05 [data-hppt-reveal-group]').evaluateAll(ns=>ns.every(n=>n.dataset.stepOrder==='1')),'调整顺序时同步组被拆散');
 await page.locator('[data-id="revealSplit"]').click();
 assert(await page.locator('#p05 [data-hppt-reveal-group]').count()===0,'拆组失败');
 await page.locator('[data-id="undo"]').click();
 assert(await page.locator('#p05 [data-hppt-reveal-group]').count()===3,'撤回未恢复同步组');
 await page.evaluate(()=>window.__htmlPptEditor.setEditing(false));
 assert(await page.locator(cards).nth(0).evaluate(n=>getComputedStyle(n).visibility==='hidden'),'播放前模块没有隐藏');
 await page.keyboard.press('PageDown');
 assert(await page.locator('#p05 [data-hppt-reveal-group]').evaluateAll(ns=>ns.every(n=>getComputedStyle(n).visibility==='visible')),'同一次翻页没有同时显示整组');
 assert(await page.locator('#p05.active').count()===1,'组出现时误翻页');
 await page.keyboard.press('PageUp');
 assert(await page.locator('#p05 [data-hppt-reveal-group]').evaluateAll(ns=>ns.every(n=>getComputedStyle(n).visibility==='hidden')),'上一页未同时隐藏整组');
 await page.evaluate(()=>window.__htmlPptEditor.setEditing(true));
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('[data-id="html"]').click()]);
 const output=path.join(temp,'export.html');await download.saveAs(output);
 await page.goto(pathToFileURL(output).href,{waitUntil:'networkidle'});
 await page.waitForFunction(()=>Boolean(window.__htmlPptEditor));
 await page.evaluate(()=>window.go(4));
 assert(await page.locator('#p05 [data-hppt-reveal-group]').count()===3,'重新打开后丢失同步组');
 await page.keyboard.press('ArrowRight');
 assert(await page.locator('#p05 [data-hppt-reveal-group]').evaluateAll(ns=>ns.every(n=>getComputedStyle(n).visibility==='visible')),'重开后同步播放失效');
 assert(!errors.length,errors.join('\n'));
 console.log(JSON.stringify({ok:true,modulePick:true,moduleDrag:true,multiSelect:true,together:true,split:true,undo:true,presenter:true,reopen:true,errors},null,2));
}finally{await browser.close();await rm(temp,{recursive:true,force:true})}
