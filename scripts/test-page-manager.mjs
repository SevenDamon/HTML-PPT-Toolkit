import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
const dashi=path.join(os.homedir(),'.codex/skills/dashiai-ppt/project');
const {chromium}=await import(pathToFileURL(path.join(dashi,'node_modules/playwright-core/index.mjs')));
const {getExportBrowserPath}=await import(pathToFileURL(path.join(dashi,'scripts/chrome-path.mjs')));
const browser=await chromium.launch({headless:true,executablePath:getExportBrowserPath()});
const temp=await mkdtemp(path.join(os.tmpdir(),'hppt-pages-'));
const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
function check(v,msg){if(!v)throw Error(msg)}
const order=()=>page.evaluate(()=>window.__htmlPptEditor.slides.map(s=>s.dataset.hpptSlideId));
try{
 await page.goto(process.argv[2],{waitUntil:'networkidle'});
 await page.evaluate(()=>window.__htmlPptEditor.setEditing(true));
 const original=await order();
 await page.locator('[data-id="pages"]').click();
 if(process.env.HPPT_QA_IMAGE)await page.screenshot({path:process.env.HPPT_QA_IMAGE});
 await page.locator('[data-page-action="next"]').click();
 let ids=await order();check(ids[1]===original[0],'前后换序失败');
 await page.locator('[data-page-action="copy"]').click();
 ids=await order();check(ids.length===original.length+1,'复制失败');
 const copy=ids[2];check(copy!==original[0],'副本标识重复');
 await page.locator('[data-page-action="delete"]').click();
 check((await order()).length===original.length,'删除失败');
 await page.locator('[data-page-action="undo"]').click();
 check((await order())[2]===copy,'撤回删除失败');
 await page.locator('[data-page-action="undo"]').click();
 check((await order()).length===original.length,'撤回复制失败');
 await page.locator('[data-page-action="redo"]').click();
 check((await order())[2]===copy,'重做失败');
 const cards=page.locator('.hppt-page-card');await cards.nth(2).dragTo(cards.nth(0));
 check((await order())[0]===copy,'拖动排序失败');
 await page.locator('[data-page-action="close"]').click();
 const duplicateIds=await page.evaluate(()=>{let ids=[...document.querySelectorAll('#deck [id]')].map(n=>n.id);return ids.filter((v,i)=>ids.indexOf(v)!==i)});
 check(!duplicateIds.length,'复制产生重复 DOM ID');
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('[data-id="html"]').click()]);
 const file=path.join(temp,'export.html');await download.saveAs(file);
 const expected=await order();
 // Standard linked decks need their assets alongside the output; the target's portable exporter embeds them.
 await page.goto(pathToFileURL(file).href,{waitUntil:'networkidle'});
 await page.waitForFunction(()=>Boolean(window.__htmlPptEditor));
 check(JSON.stringify(await order())===JSON.stringify(expected),'重新打开页序丢失');
 await page.evaluate(()=>{window.__htmlPptEditor.setEditing(false);window.go(0)});
 await page.keyboard.press('ArrowRight');
 check(await page.evaluate(()=>window.__htmlPptEditor.slides[1].classList.contains('active')),'重开后的方向键翻页失败');
 check(!errors.length,errors.join('\n'));
 const sdk=await readFile(new URL('../editor/html-ppt-editor.js',import.meta.url),'utf8');
 const wise=await browser.newPage();
 await wise.setContent('<html data-runtime="wise-ppt-deck"><head><style>.slide{width:1920px;height:1080px}</style></head><body><div id="deck"><div id="deck-stage"><div id="track"><section class="slide" id="w1"><h1>第一页</h1></section><section class="slide" id="w2"><h1>第二页</h1></section></div></div></div></body></html>');
 await wise.addScriptTag({content:sdk});
 await wise.waitForFunction(()=>Boolean(window.__htmlPptEditor));
 await wise.evaluate(()=>window.__htmlPptEditor.setEditing(true));
 await wise.locator('[data-id="pages"]').click();
 await wise.locator('[data-page-action="copy"]').click();
 check(await wise.locator('#track>.slide').count()===3,'Wise 复制失败');
 await wise.locator('[data-page-action="close"]').click();
 await wise.evaluate(()=>{window.__htmlPptEditor.setEditing(false);window.go(2)});
 check(await wise.evaluate(()=>document.querySelector('#track').style.transform.includes('-3840')),'Wise 轨道定位失败');
 await wise.close();
 console.log(JSON.stringify({ok:true,pages:expected.length,reorder:true,copy:true,delete:true,undoRedo:true,drag:true,reopen:true,keyboard:true,errors},null,2));
}finally{await browser.close();await rm(temp,{recursive:true,force:true})}
